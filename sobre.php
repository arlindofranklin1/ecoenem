            <h2>Objetivo do Site</h2>

            <p>
                O EcoENEM foi desenvolvido por três estudantes do curso Técnico em Informática do IFPB – Campus Santa
                Luzia. O projeto tem como principal objetivo auxiliar estudantes no aprendizado de Ecologia, conteúdo
                essencial da disciplina de Biologia e frequentemente abordado no ENEM e em diversos vestibulares. A
                plataforma oferece conteúdos explicativos organizados por temas, questões para treinamento e revisão dos
                conhecimentos, além da EcoIA, uma inteligência artificial desenvolvida para responder dúvidas
                relacionadas à Ecologia. Nosso propósito é tornar o estudo mais acessível, dinâmico e eficiente,
                contribuindo para a preparação dos estudantes para provas e avaliações.
